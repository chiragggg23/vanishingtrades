// Writes TRANSLATIONS_TO_REVIEW.md at the repo root: every UI string (key, English, Kannada,
// Hindi) plus the Kannada/Hindi demo story text, for a native speaker to check.
// Usage: npm run translations:review
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadLocale } from './i18n-keys.mjs';
import { seedTextsForReview } from '../../shared/seed.js';

const root = join(import.meta.dirname, '..', '..');
const en = loadLocale('en');
const kn = loadLocale('kn');
const hi = loadLocale('hi');
const cell = (s) =>
  String(s ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');

const keys = Object.keys(en).sort();
const missing = keys.filter((k) => !(k in kn) || !(k in hi));
const groups = {};
for (const k of keys) (groups[k.split('.')[0]] ||= []).push(k);

let md = `# Translations to review

Generated by \`npm run translations:review\` (client) from \`client/src/i18n/locales/*.json\` and
\`shared/seed.js\`. Do not edit by hand: fix the locale files and run the script again.

The Kannada and Hindi text was drafted for this project and has **not yet been checked by a native
speaker**. Please read each row and fix anything stiff, wrong or too formal. Keep the brand name
(VanishingTrades) and font names in Latin script. Placeholders like \`{{name}}\` must stay exactly
as they are. Keys ending in \`_one\` / \`_other\` are singular and plural forms.

- UI strings: ${keys.length}
- Strings missing a Kannada or Hindi version: ${missing.length}
- Demo world texts (artisan bios, piece names, story lines): ${seedTextsForReview().length}

## How to review

1. Mark a row by writing your correction in the locale file under the same key.
2. Look especially at: plurals (\`_one\`/\`_other\`), the tone of the home page and error messages,
   and craft names, which have local spellings.
3. Run \`npm run translations:review\` and \`npm test\` in \`client/\` afterwards.

`;
for (const [group, ks] of Object.entries(groups)) {
  md += `\n## UI: ${group}\n\n| Key | English | Kannada | Hindi |\n| --- | --- | --- | --- |\n`;
  for (const k of ks) md += `| \`${k}\` | ${cell(en[k])} | ${cell(kn[k])} | ${cell(hi[k])} |\n`;
}
md += `\n## Demo world text (shared/seed.js)\n\nArtisan bios and piece names are in English and Kannada; story lines are in the language the\nstory was told in, next to the English translation shown in the archive.\n\n| Key | English | Kannada | Hindi |\n| --- | --- | --- | --- |\n`;
for (const r of seedTextsForReview())
  md += `| \`${r.key}\` | ${cell(r.en)} | ${cell(r.kn)} | ${cell(r.hi)} |\n`;

writeFileSync(join(root, 'TRANSLATIONS_TO_REVIEW.md'), md);
console.log(
  `Wrote TRANSLATIONS_TO_REVIEW.md: ${keys.length} UI strings, ${seedTextsForReview().length} demo texts, ${missing.length} missing.`,
);
